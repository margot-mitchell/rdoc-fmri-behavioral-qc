# Rules for every task, matched by metric-name prefix:
# (prefix, threshold name, direction). Any other metric ending in '_rt' that has
# no rule of its own is checked against RT_THRESHOLD.
COMMON_RULES: List[Tuple[str, str, str]] = [
    ('proportion_feedback', 'PROPORTION_FEEDBACK_THRESHOLD', 'max'),
    ('n_trials_in_longest_omission_sequence', 'LONGEST_OMISSION_SEQUENCE', 'max'),
]

# Flag only when every metric in a group is below its minimum; each metric in
# the group is then reported as its own flag row.
